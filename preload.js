const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  cargar: () => ipcRenderer.invoke('datos:cargar'),
  guardar: (texto) => ipcRenderer.invoke('datos:guardar', texto),
  guardarAlCerrar: (texto) => ipcRenderer.sendSync('datos:guardarSync', texto),
  guardarClaves: (claves) => ipcRenderer.invoke('claves:guardar', claves),
  infoClaves: () => ipcRenderer.invoke('claves:info'),
  leerRecursosTablero: (id) => ipcRenderer.invoke('tablero:leerRecursos', id),
  guardarRecursosTablero: (id, assets) => ipcRenderer.invoke('tablero:guardarRecursos', { id, assets }),
  registroLeer: () => ipcRenderer.invoke('registro:leer'),
  registroAgregar: (lista) => ipcRenderer.invoke('registro:agregar', lista),
  registroAgregarSync: (lista) => ipcRenderer.sendSync('registro:agregarSync', lista),
  registroReemplazar: (lista) => ipcRenderer.invoke('registro:reemplazar', lista),
  limpiarRecursosTableros: (ids) => ipcRenderer.invoke('tablero:limpiar', ids),
  ortografia: (activo) => ipcRenderer.invoke('ortografia:activar', activo),
  infoAlmacen: () => ipcRenderer.invoke('almacen:info'),
  borrarCopiaAntes2: () => ipcRenderer.invoke('almacen:borrarAntes2'),
  ubicacionDatos: () => ipcRenderer.invoke('datos:ubicacion'),
  abrirCarpetaDatos: () => ipcRenderer.invoke('datos:abrirCarpeta'),
  exportarRespaldo: (estado) => ipcRenderer.invoke('respaldo:exportar', estado),
  importarRespaldo: () => ipcRenderer.invoke('respaldo:importar'),
  confirmarRestauracion: () => ipcRenderer.invoke('respaldo:confirmarRestauracion'),
  listarRespaldosAuto: () => ipcRenderer.invoke('respaldo:listarAuto'),
  restaurarRespaldoAuto: (nombre) => ipcRenderer.invoke('respaldo:restaurarAuto', nombre),
  exportarWord: (payload) => ipcRenderer.invoke('word:planeacion', payload),
  exportarWordCurricular: (tipo, nombreArchivo, payload) => ipcRenderer.invoke('word:curricular', { tipo, nombreArchivo, payload }),
  infoVersion: () => ipcRenderer.invoke('act:info'),
  buscarActualizacion: () => ipcRenderer.invoke('act:buscar'),
  descargarActualizacion: () => ipcRenderer.invoke('act:descargar'),
  instalarActualizacion: () => ipcRenderer.invoke('act:instalar'),
  paginaDescargas: () => ipcRenderer.invoke('act:pagina'),
  alAcercaDe: (fn) => ipcRenderer.on('menu:acerca', () => fn()),
  alEstadoActualizacion: (fn) => ipcRenderer.on('act:estado', (_e, d) => fn(d)),
  elegirCarpetaNube: () => ipcRenderer.invoke('nube:elegir'),
  configurarNube: (c) => ipcRenderer.invoke('nube:configurar', c),
  respaldarNube: () => ipcRenderer.invoke('nube:respaldar'),
  exportarPaquete: (nombre, contenido) => ipcRenderer.invoke('paquete:exportar', { nombre, contenido }),
  abrirPaquete: () => ipcRenderer.invoke('paquete:abrir'),
  guardarExcel: (datos) => ipcRenderer.invoke('excel:guardar', datos),
  guardarCSV: (nombre, contenido) => ipcRenderer.invoke('csv:guardar', { nombre, contenido }),
  sugerirIA: (payload) => ipcRenderer.invoke('ia:sugerir', payload),
  abrirTabla: () => ipcRenderer.invoke('tabla:abrir'),
  transcribir: (d) => ipcRenderer.invoke('ia:transcribir', d),
  modelosIA: (d) => ipcRenderer.invoke('ia:modelos', d),
  iaLocalEstado: () => ipcRenderer.invoke('ialocal:estado'),
  iaLocalInstalar: (d) => ipcRenderer.invoke('ialocal:instalar', d),
  iaLocalCancelar: () => ipcRenderer.invoke('ialocal:cancelar'),
  iaLocalQuitar: () => ipcRenderer.invoke('ialocal:quitar'),
  iaLocalAbrirCarpeta: () => ipcRenderer.invoke('ialocal:abrirCarpeta'),
  alProgresoIALocal: (fn) => ipcRenderer.on('ialocal:progreso', (_e, p) => fn(p)),
  guardarPDF: (datos) => ipcRenderer.invoke('pdf:html', datos),
  qrIniciar: (d) => ipcRenderer.invoke('qr:iniciar', d),
  qrCerrar: () => ipcRenderer.invoke('qr:cerrar'),
  qrReabrir: (min) => ipcRenderer.invoke('qr:reabrir', min),
  qrDetener: () => ipcRenderer.invoke('qr:detener'),
  qrEstado: () => ipcRenderer.invoke('qr:estado'),
  qrAbrirEnEquipo: (url) => ipcRenderer.invoke('qr:abrirEnEquipo', url),
  alEventoQR: (fn) => ipcRenderer.on('qr:evento', (_e, d) => fn(d)),
  // Celular del docente
  celActivar: (activo) => ipcRenderer.invoke('cel:activar', activo),
  alSolicitudCelular: (fn) => ipcRenderer.on('cel:solicitud', (_e, d) => fn(d)),
  responderCelular: (id, codigo, datos) => ipcRenderer.send('cel:respuesta', { id, codigo, datos }),
  // Clave de acceso
  accesoEstado: () => ipcRenderer.invoke('acceso:estado'),
  accesoDesbloquear: (clave) => ipcRenderer.invoke('acceso:desbloquear', clave),
  accesoBloquear: () => ipcRenderer.invoke('acceso:bloquear'),
  accesoActivar: (clave, minutos) => ipcRenderer.invoke('acceso:activar', { clave, minutos }),
  accesoCambiar: (actual, nueva) => ipcRenderer.invoke('acceso:cambiar', { actual, nueva }),
  accesoDesactivar: (actual) => ipcRenderer.invoke('acceso:desactivar', actual),
  accesoRecuperar: (codigo, nueva) => ipcRenderer.invoke('acceso:recuperar', { codigo, nueva }),
  accesoMinutos: (minutos) => ipcRenderer.invoke('acceso:minutos', minutos),
  // Años anteriores
  aniosListar: () => ipcRenderer.invoke('anios:listar'),
  aniosLeer: (id) => ipcRenderer.invoke('anios:leer', id),
  aniosArchivar: (texto) => ipcRenderer.invoke('anios:archivar', texto),
  aniosEliminar: (id) => ipcRenderer.invoke('anios:eliminar', id),
  aniosImportar: () => ipcRenderer.invoke('anios:importar'),
});
